// Package deadlock містить практичне застосування аналізу з
// Частини 2 домашньої роботи: той самий дедлок із завдання,
// але як тестована функція, яку потрібно виправити.
//
// Оригінальний баг (для довідки — саме цей код ви аналізуєте у
// deadlock-analysis.md):
//
//	var wg sync.WaitGroup
//	ch := make(chan int)
//	wg.Add(1)
//	go func() {
//	    ch <- 42
//	    wg.Done()
//	}()
//	wg.Wait()       // <-- блокується тут: горутина застрягла на
//	                //     "ch <- 42", бо ніхто ще не читає з ch
//	fmt.Println(<-ch)
package deadlock

// Run повертає 42, отримане від горутини через небуферизований канал.
//
// WaitGroup тут не потрібна: операція отримання <-ch сама є точкою
// синхронізації — вона блокує Run, доки горутина не надішле значення,
// і гарантує happens-before між відправленням і отриманням.
func Run() int {
	ch := make(chan int)

	go func() {
		ch <- 42
	}()

	return <-ch
}
